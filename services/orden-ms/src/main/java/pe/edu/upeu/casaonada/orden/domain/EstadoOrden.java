package pe.edu.upeu.casaonada.orden.domain;

public enum EstadoOrden {
 VALIDANDO_RESERVA,BLOQUEANDO,ESPERANDO_PAGO,GENERANDO_CONTRATO,CONFIRMANDO_PROPIEDAD,CONVIRTIENDO_RESERVA,
 CONFIRMADA,CANCELANDO_CONTRATO,REEMBOLSANDO_PAGO,LIBERANDO_PROPIEDAD,CANCELANDO_RESERVA,CANCELADA;
 public boolean terminal(){return this==CONFIRMADA||this==CANCELADA;}
 public boolean compensando(){return this==CANCELANDO_CONTRATO||this==REEMBOLSANDO_PAGO||this==LIBERANDO_PROPIEDAD||this==CANCELANDO_RESERVA;}
}
